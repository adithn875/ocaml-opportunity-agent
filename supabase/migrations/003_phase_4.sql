create table public.app_admins (
    user_id uuid primary key references auth.users(id) on delete cascade
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1 from public.app_admins where user_id = auth.uid()
    );
$$;

create table public.source_runs (
    id bigint generated by default as identity primary key,
    source_run_key text not null unique,
    source text not null,
    started_at timestamptz not null,
    finished_at timestamptz not null,
    duration_seconds numeric not null,
    status text not null check (status in ('ok', 'failed')),
    new_items integer not null default 0,
    error text
);

create index source_runs_source_started_index
    on public.source_runs (source, started_at desc);

alter table public.app_admins enable row level security;
alter table public.source_runs enable row level security;

grant execute on function public.is_admin() to authenticated;
grant select, update on public.employer_submissions to authenticated;
grant select on public.source_runs to authenticated;

create policy "admins manage employer submissions"
    on public.employer_submissions for all
    using (public.is_admin())
    with check (public.is_admin());

create policy "admins read source health"
    on public.source_runs for select
    using (public.is_admin());
