-- Per-listing freshness and community moderation.
-- `last_seen_at` means a successful collector most recently observed the
-- listing at its canonical source; it is not an assertion that a human reviewed it.

alter table public.jobs
    add column if not exists last_seen_at timestamptz;

update public.jobs
set last_seen_at = coalesce(last_seen_at, first_seen, now())
where last_seen_at is null;

create index if not exists jobs_last_seen_at_index
    on public.jobs (last_seen_at desc);

create table public.job_reports (
    id bigint generated by default as identity primary key,
    job_id bigint not null references public.jobs(id) on delete cascade,
    reported_by uuid not null default auth.uid() references auth.users(id) on delete cascade,
    report_type text not null default 'stale_or_incorrect'
        check (report_type in ('stale_or_incorrect')),
    status text not null default 'pending'
        check (status in ('pending', 'resolved', 'dismissed')),
    created_at timestamptz not null default now(),
    reviewed_at timestamptz,
    unique (job_id, reported_by)
);

create index job_reports_pending_index
    on public.job_reports (status, created_at);

alter table public.job_reports enable row level security;

grant select, insert on public.job_reports to authenticated;
grant update on public.job_reports to authenticated;

create policy "users submit and read their job reports"
    on public.job_reports for select
    using (auth.uid() = reported_by);

create policy "users submit job reports"
    on public.job_reports for insert
    with check (
        auth.uid() = reported_by
        and status = 'pending'
        and report_type = 'stale_or_incorrect'
    );

create policy "admins manage job reports"
    on public.job_reports for all
    using (public.is_admin())
    with check (public.is_admin());
