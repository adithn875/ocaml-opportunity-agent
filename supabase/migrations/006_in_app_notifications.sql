-- Durable, user-owned notification inbox and optional Web Push subscriptions.

create table public.user_notification_states (
    user_id uuid primary key references auth.users(id) on delete cascade,
    last_checked_at timestamptz not null default now()
);

create table public.user_notifications (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    job_id bigint not null references public.jobs(id) on delete cascade,
    created_at timestamptz not null default now(),
    read_at timestamptz,
    push_sent_at timestamptz,
    unique (user_id, job_id)
);

create index user_notifications_user_created_index
    on public.user_notifications (user_id, created_at desc);

create table public.web_push_subscriptions (
    endpoint text primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    subscription jsonb not null,
    created_at timestamptz not null default now()
);

alter table public.user_notification_states enable row level security;
alter table public.user_notifications enable row level security;
alter table public.web_push_subscriptions enable row level security;

grant select, insert, update on public.user_notification_states to authenticated;
grant select, update on public.user_notifications to authenticated;
grant select, insert, delete on public.web_push_subscriptions to authenticated;

create policy "users manage their notification state"
    on public.user_notification_states for all
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

create policy "users manage their inbox"
    on public.user_notifications for all
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

create policy "users manage their push subscription"
    on public.web_push_subscriptions for all
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);
