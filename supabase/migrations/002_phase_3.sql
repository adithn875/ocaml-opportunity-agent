create table public.user_profiles (
    user_id uuid primary key references auth.users(id) on delete cascade,
    skills text[] not null default '{}',
    locations text[] not null default '{}',
    remote_preference text not null default 'any'
        check (remote_preference in ('any', 'remote', 'onsite')),
    minimum_score numeric not null default 0 check (minimum_score between 0 and 100),
    updated_at timestamptz not null default now()
);

create table public.job_feedback (
    user_id uuid not null references auth.users(id) on delete cascade,
    job_id bigint not null references public.jobs(id) on delete cascade,
    label text not null check (label in ('interested', 'not_relevant')),
    updated_at timestamptz not null default now(),
    primary key (user_id, job_id)
);

create table public.job_applications (
    user_id uuid not null references auth.users(id) on delete cascade,
    job_id bigint not null references public.jobs(id) on delete cascade,
    status text not null check (status in ('interested', 'applied', 'interviewing', 'rejected')),
    updated_at timestamptz not null default now(),
    primary key (user_id, job_id)
);

create table public.employer_submissions (
    id bigint generated by default as identity primary key,
    submitted_by uuid not null default auth.uid() references auth.users(id) on delete cascade,
    title text not null,
    company text not null,
    source_url text not null,
    location text,
    description text,
    status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
    created_at timestamptz not null default now()
);

alter table public.user_profiles enable row level security;
alter table public.job_feedback enable row level security;
alter table public.job_applications enable row level security;
alter table public.employer_submissions enable row level security;

grant select, insert, update, delete on public.user_profiles to authenticated;
grant select, insert, update, delete on public.job_feedback to authenticated;
grant select, insert, update, delete on public.job_applications to authenticated;
grant insert on public.employer_submissions to authenticated;

create policy "users manage their profile"
    on public.user_profiles for all
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

create policy "users manage their feedback"
    on public.job_feedback for all
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

create policy "users manage their applications"
    on public.job_applications for all
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

create policy "signed-in users submit jobs"
    on public.employer_submissions for insert
    with check (auth.uid() = submitted_by and status = 'pending');
