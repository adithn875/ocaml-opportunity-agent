create table public.jobs (
    id bigint generated by default as identity primary key,
    source_url text not null unique,
    title text not null,
    company text,
    employment_type text,
    location text,
    remote text,
    posted_date text,
    deadline text,
    source text,
    description text,
    deterministic_score numeric,
    llm_score numeric,
    final_score numeric,
    first_seen timestamptz,
    updated_at timestamptz not null default now()
);

create index jobs_final_score_index on public.jobs (final_score desc);
create index jobs_source_index on public.jobs (source);

create table public.saved_jobs (
    user_id uuid not null references auth.users(id) on delete cascade,
    job_id bigint not null references public.jobs(id) on delete cascade,
    created_at timestamptz not null default now(),
    primary key (user_id, job_id)
);

create table public.alert_preferences (
    user_id uuid primary key references auth.users(id) on delete cascade,
    minimum_score numeric not null default 0 check (minimum_score between 0 and 100),
    frequency text not null default 'daily' check (frequency in ('daily', 'weekly')),
    updated_at timestamptz not null default now()
);

alter table public.jobs enable row level security;
alter table public.saved_jobs enable row level security;
alter table public.alert_preferences enable row level security;

grant usage on schema public to anon, authenticated;
grant select on public.jobs to anon, authenticated;
grant select, insert, delete on public.saved_jobs to authenticated;
grant select, insert, update, delete on public.alert_preferences to authenticated;

create policy "public jobs are readable"
    on public.jobs for select using (true);

create policy "users manage their saved jobs"
    on public.saved_jobs for all
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

create policy "users manage their alert preferences"
    on public.alert_preferences for all
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);
